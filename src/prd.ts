// PRD 说明文档中心仓库（支持编辑保存）
const state = reactive<{ docs: Record<string, PrdDoc>; visible: boolean; dialogDocKey: string | null }>({
  docs: {},
  visible: true,
  dialogDocKey: null
})

function def(key: string, doc: PrdDoc) {
  if (!state.docs[key]) state.docs[key] = doc
}

