export const ALL_POINT_GROUPS: PointGroup[] = [
  'structure',
  'env',
  'traffic',
  'monitor',
  'mep',
]
export const MODULE_POINT_GROUPS: Record<string, readonly PointGroup[]> = {
  overview: ALL_POINT_GROUPS,
  traffic: ['structure', 'traffic'],
  maintenance: ['structure', 'monitor'],
  monitoring: ['structure', 'env', 'monitor'],
  emergency: ['structure', 'env', 'mep'],
  service: ['structure'],
  asset: ALL_POINT_GROUPS,
}
export function defaultPointGroups(path: string): readonly PointGroup[] {
  return MODULE_POINT_GROUPS[path.replace(/^\//, '')] ?? ALL_POINT_GROUPS
}
export function alertScenePoints(
  alerts: readonly TunnelAlert[] = DEMO_ALERTS,
): ScenePoint[] {
  return alerts.map((alert) => ({
    id: alert.pointId,
    name: alert.title,
    stake: alert.stake,
    kind: alert.kind,
    group: alert.group,
    status: alert.level === 'critical' ? 'alarm' : 'warn',
    left: '50%',
    top: '50%',
    leftNum: 50,
    scale: 1,
    value: `模拟${alert.source}事件`,
    alarm: `${alert.description}（模拟）`,
    simulated: true,
    alertId: alert.id,
  }))
}
