/** 保留页面业务 ID；共享目录补足环境/监测图层，告警与视频锚点始终可精确定位。 */
export function mergeScenePoints(
  pagePoints: readonly ScenePoint[],
): ScenePoint[] {
  const signatures = new Set(pagePoints.map((p) => `${p.kind}|${p.stake}`))
  const ids = new Set(pagePoints.map((p) => p.id))
  const base = BASE_SCENE_POINTS.filter(
    (p) => !ids.has(p.id) && !signatures.has(`${p.kind}|${p.stake}`),
  )
  const merged = new Map(
    [...base, ...pagePoints, ...CAMERA_SCENE_POINTS, ...alertScenePoints()].map(
      (p) => [p.id, p],
    ),
  )
  return [...merged.values()].map((point) => ({
    ...point,
    simulated: point.simulated ?? true,
  }))
}
